/* What the screen shows. The picture fills the panel; the round edge cuts
 * its corners. */
struct View {
	const uint16_t *image; /* 96 x 96 RGB565 */
	const Found *res;
	const char *caption;
};

constexpr int kImgX = 24;
constexpr int kImgY = 6;
constexpr int kImgScale = 2;

const uint16_t kClassColor[kClasses] = {
	COLOR_BLACK, RGB565(255, 220, 0), COLOR_WHITE, RGB565(255, 50, 40), RGB565(70, 150, 255),
};

void draw_marker(const Detection &d, int half)
{
	const int cx = kImgX + static_cast<int>(d.x * kSide * kImgScale);
	const int cy = kImgY + static_cast<int>(d.y * kSide * kImgScale);
	const char *label = kNames[d.cls];
	const int tw = static_cast<int>(strlen(label)) * SCREEN_FONT_W;
	int tx = cx - tw / 2;
	int ty = cy + half + 3;

	/* A square in the colour of the class with a black edge either side,
	 * so it shows on any brick and any desk. */
	screen_frame(cx - half - 1, cy - half - 1, 2 * half + 2, 2 * half + 2, 4, COLOR_BLACK);
	screen_frame(cx - half, cy - half, 2 * half, 2 * half, 2, kClassColor[d.cls]);
	screen_fill(cx - 1, cy - 1, 3, 3, kClassColor[d.cls]);

	if (ty + SCREEN_FONT_H + 2 > kImgY + kSide * kImgScale) {
		ty = cy - half - SCREEN_FONT_H - 4;
	}
	tx = tx < kImgX ? kImgX : tx;
	if (tx + tw > kImgX + kSide * kImgScale) {
		tx = kImgX + kSide * kImgScale - tw;
	}
	screen_fill(tx - 1, ty - 1, tw + 2, SCREEN_FONT_H + 2, COLOR_BLACK);
	screen_text(tx, ty, label, 1, kClassColor[d.cls]);
}

void draw_view(void *ctx)
{
	const View *v = static_cast<const View *>(ctx);
	const Found &res = *v->res;
	char text[24];

	screen_rgb565(kImgX, kImgY, v->image, kSide, kSide, kImgScale);
	if (res.has_bin) {
		draw_marker(res.bin, 14);
	}
	for (int i = 0; i < res.n; ++i) {
		draw_marker(res.bricks[i], 8);
	}

	snprintk(text, sizeof(text), "n=%d %ums", res.n, (res.us + 500) / 1000);
	screen_text(120 - SCREEN_FONT_W * static_cast<int>(strlen(text)), 202, text, 2, COLOR_WHITE);
	screen_text(120 - SCREEN_FONT_W / 2 * static_cast<int>(strlen(v->caption)), 222, v->caption,
		    1, res.has_bin ? kClassColor[kBin] : COLOR_GREY);
}
